-- Double-entry ledger schema. Accounts, immutable journal entries, append-only postings.
-- Balances are DERIVED (sum of an account's postings), never stored as a column — the posting
-- log is the source of truth, which is what makes the ledger auditable and reconcilable.

create table account (
    id         bigint generated by default as identity primary key,
    code       varchar(64)  not null unique,   -- stable business key, e.g. 'CUSTOMER_WALLET:cust-123'
    type       varchar(16)  not null,          -- AccountType: ASSET/LIABILITY/EQUITY/REVENUE/EXPENSE
    currency   varchar(3)   not null,          -- ISO-4217
    created_at timestamp    not null
);

create table journal_entry (
    id              bigint generated by default as identity primary key,
    idempotency_key varchar(100) not null unique,   -- source event id: a replay posts exactly once
    reference       varchar(64)  not null,          -- business key (orderRef / trade id)
    status          varchar(16)  not null,          -- JournalEntryStatus lifecycle
    currency        varchar(3)   not null,
    created_at      timestamp    not null,
    version         bigint       not null default 0 -- optimistic lock for status transitions
);
-- reconciliation + audit group by the business reference
create index idx_journal_entry_reference on journal_entry (reference);

create table posting (
    id               bigint generated by default as identity primary key,
    journal_entry_id bigint      not null references journal_entry (id),
    account_id       bigint      not null references account (id),
    direction        varchar(6)  not null,                 -- DEBIT | CREDIT
    amount_minor     bigint      not null check (amount_minor > 0),  -- minor units; direction holds the sign
    currency         varchar(3)  not null,
    created_at       timestamp   not null
);
create index idx_posting_journal_entry on posting (journal_entry_id);
create index idx_posting_account on posting (account_id);
